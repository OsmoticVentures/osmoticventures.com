// Regenerates src/app/(site)/blur.ts: a 12px blurred data URL per photo, so an image opens on its own colours.
import { createRequire } from "node:module";
const sharp = createRequire(import.meta.url)(process.env.SHARP_PATH || "sharp");
import { writeFileSync } from "node:fs";
const files = ["/img/juan-usc.png", "/img/poster-bcla.jpg", "/img/poster-cpbh.jpg", "/img/poster-metaba.jpg", "/img/phil-sell-metaba.png"];
const out = {};
for (const f of files) {
  const buf = await sharp(`public${f}`).resize(12).flatten({ background: "#13201a" }).jpeg({ quality: 50 }).toBuffer();
  out[f] = `data:image/jpeg;base64,${buf.toString("base64")}`;
}
writeFileSync("src/app/(site)/blur.ts", `// Generated by scripts/blur.mjs. Do not edit.\nexport const BLUR: Record<string, string> = ${JSON.stringify(out, null, 2)};\n`);
